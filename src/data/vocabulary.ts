export function getWordsByLevel(level: CEFRLevel): VocabularyWord[] {
  return VOCABULARY_DATA.filter((w) => w.level === level);
}

export function getWordsByCategory(category: string): VocabularyWord[] {
  if (!category || category === 'all') return VOCABULARY_DATA;
  return VOCABULARY_DATA.filter((w) => w.category === category);
}

export function getFilteredWords(level: CEFRLevel, category?: string): VocabularyWord[] {
  let list = VOCABULARY_DATA.filter((w) => w.level === level);
  if (category && category !== 'all') {
    list = list.filter((w) => w.category === category);
  }
  return list;
}

